    private void login() {
        String host = txtHost.getText().trim();
        String username = txtUsername.getText().trim();

        if (host.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Vui lòng nhập địa chỉ Server.");
            return;
        }

        if (username.isEmpty() || username.contains(" ")
                || username.contains("|")) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Tên đăng nhập không hợp lệ.");
            return;
        }

        btnLogin.setEnabled(false);
        lblStatus.setText("Đang kết nối...");

        new Thread(() -> {
            java.net.Socket socket = null;

            try {
                socket = new java.net.Socket(host, 5000);

                java.io.BufferedReader in =
                    new java.io.BufferedReader(
                        new java.io.InputStreamReader(socket.getInputStream(), java.nio.charset.StandardCharsets.UTF_8));

                java.io.PrintWriter out =
                    new java.io.PrintWriter(socket.getOutputStream(), true, java.nio.charset.StandardCharsets.UTF_8);

                out.println("LOGIN " + username);

                String response = in.readLine();

                if (response == null || !response.startsWith("OK|")) {
                    String error = response == null ? "Server đã đóng kết nối." : response.replace("|", ": ");

                    socket.close();

                    javax.swing.SwingUtilities.invokeLater(() -> {
                        javax.swing.JOptionPane.showMessageDialog(
                            this, error, "Đăng nhập thất bại",
                            javax.swing.JOptionPane.ERROR_MESSAGE);

                    btnLogin.setEnabled(true);
                    lblStatus.setText("Đăng nhập thất bại");
                    });

                    return;
                }

                java.net.Socket connectedSocket = socket;
                String successMessage = response.substring(3);

                javax.swing.SwingUtilities.invokeLater(() -> {
                    frmChat form = new frmChat(
                        username, connectedSocket, in, out,
                        successMessage);

                    form.setVisible(true);
                    form.startReceiver();
                    form.refreshUsers();

                    dispose();
                });

            } catch (java.io.IOException ex) {
                if (socket != null) {
                    try {
                        socket.close();
                    } catch (java.io.IOException ignored) {
                    }
                }

                String error = "Không thể kết nối Server: " + ex.getMessage();

                javax.swing.SwingUtilities.invokeLater(() -> {
                    javax.swing.JOptionPane.showMessageDialog(
                        this, error, "Lỗi kết nối",
                        javax.swing.JOptionPane.ERROR_MESSAGE);

                    btnLogin.setEnabled(true);
                    lblStatus.setText("Chưa kết nối Server");
                });
            }
        }, "Login-Thread").start();
    }

